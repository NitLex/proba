export function creativeBriefForVertical(verticalKey = '') {
  return CREATIVE_BY_VERTICAL[verticalKey] || CREATIVE_BY_VERTICAL.default;
}

/** System-style instructions for creative agent (Cursor spawn + pipeline). */
export function creativeAgentSystemPrompt(verticalKey = '') {
  const brief = creativeBriefForVertical(verticalKey);
  return [
    `Ты ${brief.role}.`,
    'Площадка: Яндекс.Директ РСЯ. Цель — качественный клик и CR, не «красивая картинка ради картинки».',
    '',
    'Жёсткие правила:',
    ...CREATIVE_HARD_RULES.map((r) => `- ${r}`),
    '',
    `Визуал: ${brief.visual}`,
    `В текстах обязательно: ${brief.must_in_copy.join('; ')}`,
    `Нельзя: ${brief.avoid.join('; ')}`,
    '',
  'Движок картинок: Cursor креатив-агент (GenerateImage). Пиши промпты подробно; референсы — если есть.',
  'Title ≤56, Text ≤81. Промокод — только если есть в оффере.',
].join('\n');
}

